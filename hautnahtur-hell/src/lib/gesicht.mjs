// Gesicht für die Zonen-Ansicht «Gesicht»: Kopf, Hals, Schulteransatz in Linienzeichnung, viewBox 0 0 240 262.
// Damen und Herren mit eigenen Proportionen; Zonen als eigene Flächen (Glasur), Ankerpunkte für die Preisschilder.
import { smooth } from './figur.mjs';

const M = (x) => 240 - x;
const spiegel = (pts) => pts.map(([x, y, c]) => [M(x), y, c]);
// Halbe Kontur (rechts, von oben nach unten) → geschlossene, symmetrische Form
const sym = (halb) => smooth([...halb, ...spiegel(halb.slice(1, -1)).reverse()]);
const ell = (cx, cy, rx, ry) => `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0Z`;
// Pfad spiegeln: nur absolute Befehle M L C Q Z mit Zahlenpaaren
const spiegelPfad = (d) => d.replace(/([MLCQ])([^MLCQZ]+)/g, (_, c, nums) => c + nums.trim().split(/[\s,]+/).map(Number).map((n, i) => (i % 2 ? n : M(n))).join(' '));
const paar = (d) => d + spiegelPfad(d);

function koerper(halsX, schulter) {
  // links unten → Hals → rechts unten (Ecken an den Bildrändern)
  const l = [[0, 262, 1], ...schulter, [halsX, 150, 1]];
  const r = spiegel(l).reverse();
  return smooth([...l, ...r]);
}

